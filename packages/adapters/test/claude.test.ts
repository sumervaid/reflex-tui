import { mkdtemp, mkdir, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { ClaudeCodeAdapter } from "../src/claude";
import { FIX_CI, toClaudeLines } from "@reflix/test-fixtures";

const NOW = new Date("2026-10-11T12:00:00Z");
const opts = { days: 7, now: NOW };
let root: string;

beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), "reflix-claude-"));
});
afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

async function writeSession(name: string, lines: Array<Record<string, unknown> | string>): Promise<string> {
  const dir = join(root, "-Users-jordan-code-app");
  await mkdir(dir, { recursive: true });
  const path = join(dir, `${name}.jsonl`);
  await writeFile(path, lines.map((l) => (typeof l === "string" ? l : JSON.stringify(l))).join("\n") + "\n");
  return path;
}

const user = (text: string, extra: Record<string, unknown> = {}) => ({
  type: "user",
  sessionId: "s1",
  timestamp: "2026-10-10T10:00:00.000Z",
  cwd: "/Users/jordan/code/app",
  message: { role: "user", content: text },
  ...extra,
});

async function parseOnly(adapter: ClaudeCodeAdapter) {
  const files = await adapter.discover(opts);
  return Promise.all(files.map((f) => adapter.parse(f, opts)));
}

describe("ClaudeCodeAdapter", () => {
  it("parses a valid fixture into requests, shell and file events", async () => {
    const { lines } = toClaudeLines(FIX_CI[0]!, new Date("2026-10-10T09:00:00Z"), "abc");
    await writeSession("abc", lines);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    const s = result!.sessions[0]!;
    expect(s.id).toBe("claude-code:abc");
    expect(s.project?.name).toBe("acme-web");
    expect(s.project?.pathHash).toMatch(/^[0-9a-f]{12}$/);
    expect(s.requests[0]!.text).toContain("CI is failing");
    expect(s.requests[0]!.text).not.toContain("npm_a1B2");
    const shells = s.events.filter((e) => e.kind === "shell");
    expect(shells.map((e) => (e.kind === "shell" ? e.command : ""))).toContain("pnpm install --frozen-lockfile");
    const failed = shells.find((e) => e.kind === "shell" && e.command === "pnpm install --frozen-lockfile");
    expect(failed && "isError" in failed && failed.isError).toBe(true);
    const files = s.events.filter((e) => e.kind === "file");
    expect(files.every((e) => e.kind === "file" && !e.path.includes("/Users/jordan"))).toBe(true);
  });

  it("skips malformed and truncated lines without dropping the session", async () => {
    await writeSession("s1", [user("fix the tests"), "{not json", '{"type":"assistant","message":{"content":[{"ty', "", user("and lint")]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.skippedRecords).toBe(2);
    expect(result!.sessions[0]!.requests.map((r) => r.text)).toEqual(["fix the tests", "and lint"]);
  });

  it("ignores unknown record types and harness-injected text", async () => {
    await writeSession("s1", [
      { type: "brand-new-type", foo: 1 },
      user("<command-name>/clear</command-name>"),
      user("Caveat: the messages below were generated by the user while running local commands."),
      user("meta", { isMeta: true }),
      user("<system-reminder>be nice</system-reminder>real question"),
    ]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.skippedRecords).toBe(0);
    expect(result!.sessions[0]!.requests.map((r) => r.text)).toEqual(["real question"]);
  });

  it("falls back to file mtime when timestamps are missing", async () => {
    await writeSession("s1", [{ ...user("hello there"), timestamp: undefined }]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.sessions[0]!.endedAt).toBeDefined();
  });

  it("drops duplicated records and sidechain (subagent) records", async () => {
    const rec = { ...user("deploy fix"), uuid: "u1" };
    await writeSession("s1", [rec, rec, { ...user("subagent chatter"), uuid: "u2", isSidechain: true }]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.sessions[0]!.requests).toHaveLength(1);
  });

  it("keeps Unicode intact", async () => {
    await writeSession("s1", [user("修复 CI 失败 🚀 — ça marche?")]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.sessions[0]!.requests[0]!.text).toBe("修复 CI 失败 🚀 — ça marche?");
  });

  it("streams a giant session and caps stored events", async () => {
    const lines: Record<string, unknown>[] = [user("big one")];
    for (let i = 0; i < 20_000; i++) {
      lines.push({
        type: "assistant",
        sessionId: "s1",
        timestamp: "2026-10-10T10:00:01.000Z",
        message: { role: "assistant", content: [{ type: "tool_use", id: `t${i}`, name: "Bash", input: { command: `echo ${i}` } }] },
      });
    }
    await writeSession("s1", lines);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.totalRecords).toBe(20_001);
    expect(result!.sessions[0]!.events.length).toBeLessThanOrEqual(3000);
  });

  it("respects --days and does not follow symlinks", async () => {
    const old = await writeSession("old", [user("ancient", { timestamp: "2026-09-01T00:00:00Z" })]);
    const { utimes } = await import("node:fs/promises");
    await utimes(old, new Date("2026-09-01"), new Date("2026-09-01"));
    await writeSession("fresh", [user("recent")]);
    await symlink("/etc/hosts", join(root, "-Users-jordan-code-app", "evil.jsonl"));
    const files = await new ClaudeCodeAdapter(root).discover(opts);
    expect(files.map((f) => f.path.split("/").pop())).toEqual(["fresh.jsonl"]);
  });

  it("reports a missing root as not found", async () => {
    const d = await new ClaudeCodeAdapter(join(root, "nope")).detect();
    expect(d.found).toBe(false);
  });
});
