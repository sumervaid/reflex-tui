import { mkdtemp, mkdir, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { ClaudeCodeAdapter } from "../src/claude";
import { MAX_EVENTS_PER_SESSION } from "../src/common";
import type { SessionEvent } from "@reflex/core";
import { FIX_CI, toClaudeLines } from "@reflex/test-fixtures";

const NOW = new Date("2026-10-11T12:00:00Z");
const opts = { days: 7, now: NOW };
let root: string;

beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), "reflex-claude-"));
});
afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

async function writeSession(name: string, lines: Array<Record<string, unknown> | string>): Promise<string> {
  const dir = join(root, "-Users-jordan-code-app");
  await mkdir(dir, { recursive: true });
  const path = join(dir, `${name}.jsonl`);
  await writeFile(path, lines.map((l) => (typeof l === "string" ? l : JSON.stringify(l))).join("\n") + "\n");
  return path;
}

const user = (text: string, extra: Record<string, unknown> = {}) => ({
  type: "user",
  sessionId: "s1",
  timestamp: "2026-10-10T10:00:00.000Z",
  cwd: "/Users/jordan/code/app",
  message: { role: "user", content: text },
  ...extra,
});

async function parseOnly(adapter: ClaudeCodeAdapter) {
  const files = await adapter.discover(opts);
  return Promise.all(files.map((f) => adapter.parse(f, opts)));
}

describe("ClaudeCodeAdapter", () => {
  it("parses a valid fixture into requests, shell and file events", async () => {
    const { lines } = toClaudeLines(FIX_CI[0]!, new Date("2026-10-10T09:00:00Z"), "abc");
    await writeSession("abc", lines);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    const s = result!.sessions[0]!;
    expect(s.id).toBe("claude-code:abc");
    expect(s.project?.name).toBe("acme-web");
    expect(s.project?.pathHash).toMatch(/^[0-9a-f]{12}$/);
    expect(s.requests[0]!.text).toContain("CI is failing");
    expect(s.requests[0]!.text).not.toContain("npm_a1B2");
    const shells = s.events.filter((e) => e.kind === "shell");
    expect(shells.map((e) => (e.kind === "shell" ? e.command : ""))).toContain("pnpm install --frozen-lockfile");
    const failed = shells.find((e) => e.kind === "shell" && e.command === "pnpm install --frozen-lockfile");
    expect(failed && "isError" in failed && failed.isError).toBe(true);
    const files = s.events.filter((e) => e.kind === "file");
    expect(files.every((e) => e.kind === "file" && !e.path.includes("/Users/jordan"))).toBe(true);
  });

  it("skips malformed and truncated lines without dropping the session", async () => {
    await writeSession("s1", [user("fix the tests"), "{not json", '{"type":"assistant","message":{"content":[{"ty', "", user("and lint")]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.skippedRecords).toBe(2);
    expect(result!.sessions[0]!.requests.map((r) => r.text)).toEqual(["fix the tests", "and lint"]);
  });

  it("ignores unknown record types and harness-injected text", async () => {
    await writeSession("s1", [
      { type: "brand-new-type", foo: 1 },
      user("<command-name>/clear</command-name>"),
      user("Caveat: the messages below were generated by the user while running local commands."),
      user("meta", { isMeta: true }),
      user("summary of earlier work. never run the tests", { isCompactSummary: true }),
      user("This session is being continued from a previous conversation that ran out of context."),
      user("<system-reminder>be nice</system-reminder>real question"),
    ]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.skippedRecords).toBe(0);
    expect(result!.sessions[0]!.requests.map((r) => r.text)).toEqual(["real question"]);
  });

  it("falls back to file mtime when timestamps are missing", async () => {
    await writeSession("s1", [{ ...user("hello there"), timestamp: undefined }]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.sessions[0]!.endedAt).toBeDefined();
  });

  it("drops duplicated records; a sidechain prompt is never a request", async () => {
    const rec = { ...user("deploy fix"), uuid: "u1" };
    await writeSession("s1", [rec, rec, { ...user("subagent chatter"), uuid: "u2", isSidechain: true }]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.sessions[0]!.requests).toHaveLength(1);
  });

  it("folds sub-agent work into the parent session, marked byAgent, after the launch", async () => {
    const toolUse = (id: string, name: string, input: Record<string, unknown>) => ({
      type: "assistant",
      sessionId: "s1",
      timestamp: "2026-10-10T10:01:00.000Z",
      cwd: "/Users/jordan/code/app",
      message: { role: "assistant", content: [{ type: "tool_use", id, name, input }] },
    });
    const toolResult = (id: string, isError = false) => ({
      type: "user",
      sessionId: "s1",
      timestamp: "2026-10-10T10:02:00.000Z",
      message: { role: "user", content: [{ type: "tool_result", tool_use_id: id, is_error: isError }] },
    });
    const side = (extra: Record<string, unknown>) => ({ timestamp: "2026-10-10T10:05:00.000Z", isSidechain: true, ...extra });
    await writeSession("s1", [
      user("review the auth module"),
      toolUse("t1", "Task", { subagent_type: "code-reviewer", prompt: "review it" }),
      // The sub-agent's own prompt, its failing shell call, its result, and its narration.
      side({ type: "user", sessionId: "sub-1", message: { role: "user", content: "review the auth module now" } }),
      side({ type: "assistant", sessionId: "sub-1", message: { role: "assistant", content: [{ type: "tool_use", id: "s1", name: "Bash", input: { command: "gh pr diff 41" } }] } }),
      side({ type: "user", sessionId: "sub-1", message: { role: "user", content: [{ type: "tool_result", tool_use_id: "s1", is_error: true }] } }),
      side({ type: "assistant", sessionId: "sub-1", message: { role: "assistant", content: [{ type: "text", text: "the diff looks fine" }] } }),
      // The parent continues after the sub-agent finished.
      { ...toolUse("t2", "Bash", { command: "git status --short" }), timestamp: "2026-10-10T10:06:00.000Z" },
      { ...toolResult("t2"), timestamp: "2026-10-10T10:07:00.000Z" },
    ]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    const s = result!.sessions[0]!;
    // The sub-agent's prompt is not a request; the parent's is.
    expect(s.requests.map((r) => r.text)).toEqual(["review the auth module"]);
    const byAgent = s.events.filter((e) => "byAgent" in e && e.byAgent);
    expect(byAgent).toHaveLength(1);
    expect(byAgent[0]).toMatchObject({ kind: "shell", command: "gh pr diff 41", isError: true, byAgent: true });
    // The delegated events sit between the launch and the parent's next call, in time order.
    const kinds = s.events.map((e) => (e.kind === "tool" ? `tool:${e.tool}` : e.kind === "shell" ? `shell:${"command" in e ? e.command : ""}` : e.kind));
    expect(kinds.indexOf("tool:Task")).toBeLessThan(kinds.indexOf("shell:gh pr diff 41"));
    expect(kinds.indexOf("shell:gh pr diff 41")).toBeLessThan(kinds.indexOf("shell:git status --short"));
    expect(s.events.every((e) => !("text" in e && e.text === "review the auth module now"))).toBe(true);
  });

  it("the event cap still holds with sub-agent work folded in", async () => {
    const events: Array<Record<string, unknown>> = [user("do it all"), {
      type: "assistant",
      sessionId: "s1",
      timestamp: "2026-10-10T10:00:00.000Z",
      message: { role: "assistant", content: [{ type: "tool_use", id: "t1", name: "Task", input: { prompt: "go" } }] },
    }];
    for (let i = 0; i < 400; i++) {
      events.push({ type: "user", sessionId: "sub-1", isSidechain: true, timestamp: "2026-10-10T10:01:00.000Z", message: { role: "user", content: "keep going" } });
      events.push({
        type: "assistant",
        sessionId: "sub-1",
        isSidechain: true,
        timestamp: "2026-10-10T10:02:00.000Z",
        message: { role: "assistant", content: [{ type: "tool_use", id: `s${i}`, name: "Bash", input: { command: `echo ${i}` } }] },
      });
    }
    await writeSession("s1", events);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    const s = result!.sessions[0]!;
    expect(s.events.length).toBeLessThanOrEqual(MAX_EVENTS_PER_SESSION);
    const byAgent = s.events.filter((e) => "byAgent" in e && e.byAgent).length;
    expect(byAgent).toBeGreaterThan(0);
    expect(s.events.length - byAgent).toBeGreaterThan(0); // the parent's own events are not crowded out
  });

  it("keeps Unicode intact", async () => {
    await writeSession("s1", [user("修复 CI 失败 🚀 — ça marche?")]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.sessions[0]!.requests[0]!.text).toBe("修复 CI 失败 🚀 — ça marche?");
  });

  it("captures thinking blocks redacted and capped, and never the raw text", async () => {
    const assistant = (content: Array<Record<string, unknown>>) => ({
      type: "assistant",
      sessionId: "s1",
      timestamp: "2026-10-10T10:01:00.000Z",
      cwd: "/Users/jordan/code/app",
      message: { role: "assistant", content },
    });
    const events: Array<Record<string, unknown>> = [
      user("fix the failing test"),
      assistant([{ type: "thinking", thinking: "the token is NPM_TOKEN=npm_a1B2c3D4e5F6g7H8i9J0k1L2m3N4o5P6q7R8, never print it" }]),
    ];
    for (let i = 0; i < 8; i++) events.push(assistant([{ type: "thinking", thinking: `consideration ${i}: ${"detailed reasoning ".repeat(12)}` }]));
    await writeSession("s1", events);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    const s = result!.sessions[0]!;
    expect(s.thinking).toBeDefined();
    expect(s.thinking).toContain("REDACTED"); // the key was redacted before storage
    expect(s.thinking).not.toContain("npm_a1B2");
    expect(s.thinking!.length).toBeLessThanOrEqual(2000); // the whole excerpt is capped
    expect(s.thinking).toContain("consideration 0"); // several blocks join into one excerpt
  });

  it("keeps a redacted excerpt of a failed tool result, and drops a leaky one", async () => {
    const toolUse = (id: string, name: string, input: Record<string, unknown>) => ({
      type: "assistant",
      sessionId: "s1",
      timestamp: "2026-10-10T10:01:00.000Z",
      message: { role: "assistant", content: [{ type: "tool_use", id, name, input }] },
    });
    const toolResult = (id: string, content: unknown, isError = true) => ({
      type: "user",
      sessionId: "s1",
      timestamp: "2026-10-10T10:02:00.000Z",
      message: { role: "user", content: [{ type: "tool_result", tool_use_id: id, content, is_error: isError }] },
    });
    await writeSession("s1", [
      user("fix the tests"),
      toolUse("t1", "Bash", { command: "pnpm test" }),
      toolResult("t1", "Error: NPM_TOKEN=npm_a1B2c3D4e5F6g7H8i9J0k1L2m3N4o5P6q7R8 missing\n    at run (x)".repeat(3)),
      toolUse("t2", "Bash", { command: "git push" }),
      toolResult("t2", "git@github.com: Permission denied (publickey)"),
      toolUse("t3", "Bash", { command: "pnpm lint" }),
      toolResult("t3", "22 passed", false),
    ]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    const s = result!.sessions[0]!;
    const shells = s.events.filter((e): e is Extract<SessionEvent, { kind: "shell" }> => e.kind === "shell");
    const failed = shells.find((e) => e.command === "pnpm test")!;
    expect(failed.isError).toBe(true);
    expect(failed.errorExcerpt).toBeDefined();
    expect(failed.errorExcerpt!.length).toBeLessThanOrEqual(200);
    expect(failed.errorExcerpt).not.toContain("npm_a1B2");
    const leaky = shells.find((e) => e.command === "git push")!;
    expect(leaky.isError).toBe(true); // still marked failed
    expect(leaky.errorExcerpt).toBeUndefined(); // the excerpt failed the leak gate
    const cleanRun = shells.find((e) => e.command === "pnpm lint")!;
    expect(cleanRun.isError).toBe(false); // the call succeeded
    expect(cleanRun.errorExcerpt).toBeUndefined(); // only failed results keep one
    expect(cleanRun.exitCode).toBeUndefined();
  });

  it("keeps the numeric exit code a failed result reports", async () => {
    const toolUse = (id: string, name: string, input: Record<string, unknown>) => ({
      type: "assistant",
      sessionId: "s1",
      timestamp: "2026-10-10T10:01:00.000Z",
      message: { role: "assistant", content: [{ type: "tool_use", id, name, input }] },
    });
    const toolResult = (id: string, content: string) => ({
      type: "user",
      sessionId: "s1",
      timestamp: "2026-10-10T10:02:00.000Z",
      message: { role: "user", content: [{ type: "tool_result", tool_use_id: id, content, is_error: true }] },
    });
    await writeSession("s1", [
      user("fix the tests"),
      toolUse("t1", "Bash", { command: "pnpm test" }),
      toolResult("t1", "Process exited with code 2\n    at run"),
      toolUse("t2", "Bash", { command: "pnpm lint" }),
      toolResult("t2", "failed with exit code: 127"),
    ]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    const shells = result!.sessions[0]!.events.filter((e): e is Extract<SessionEvent, { kind: "shell" }> => e.kind === "shell");
    expect(shells.find((e) => e.command === "pnpm test")?.exitCode).toBe(2);
    expect(shells.find((e) => e.command === "pnpm lint")?.exitCode).toBe(127);
  });

  it("streams a giant session and caps stored events", async () => {
    const lines: Record<string, unknown>[] = [user("big one")];
    for (let i = 0; i < 20_000; i++) {
      lines.push({
        type: "assistant",
        sessionId: "s1",
        timestamp: "2026-10-10T10:00:01.000Z",
        message: { role: "assistant", content: [{ type: "tool_use", id: `t${i}`, name: "Bash", input: { command: `echo ${i}` } }] },
      });
    }
    await writeSession("s1", lines);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.totalRecords).toBe(20_001);
    expect(result!.sessions[0]!.events.length).toBeLessThanOrEqual(3000);
  });

  it("respects --days and does not follow symlinks", async () => {
    const old = await writeSession("old", [user("ancient", { timestamp: "2026-09-01T00:00:00Z" })]);
    const { utimes } = await import("node:fs/promises");
    await utimes(old, new Date("2026-09-01"), new Date("2026-09-01"));
    await writeSession("fresh", [user("recent")]);
    await symlink("/etc/hosts", join(root, "-Users-jordan-code-app", "evil.jsonl"));
    const files = await new ClaudeCodeAdapter(root).discover(opts);
    expect(files.map((f) => f.path.split("/").pop())).toEqual(["fresh.jsonl"]);
  });

  it("counts each message's token usage once and records Skill tool calls", async () => {
    const usage = { input_tokens: 10, output_tokens: 5, cache_read_input_tokens: 100, cache_creation_input_tokens: 20 };
    const assistant = (id: string, block: Record<string, unknown>) => ({
      type: "assistant",
      sessionId: "s1",
      timestamp: "2026-10-10T10:00:01.000Z",
      message: { role: "assistant", id, usage, content: [block] },
    });
    await writeSession("s1", [
      user("review this PR"),
      assistant("m1", { type: "text", text: "Looking." }),
      assistant("m1", { type: "tool_use", id: "t1", name: "Skill", input: { skill: "review-pr" } }),
      assistant("m2", { type: "tool_use", id: "t2", name: "Skill", input: { skill: "$(rm -rf /)" } }),
    ]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    const s = result!.sessions[0]!;
    expect(s.usage).toEqual({ input: 20, output: 10, cacheRead: 200, cacheWrite: 40 });
    const skills = s.events.filter((e) => e.kind === "tool" && e.tool === "Skill").map((e) => (e.kind === "tool" ? e.skill : ""));
    expect(skills).toEqual(["review-pr", undefined]);
  });

  it("records which cache writes were for 1 hour", async () => {
    const usage = { input_tokens: 1, output_tokens: 1, cache_creation_input_tokens: 30, cache_creation: { ephemeral_5m_input_tokens: 10, ephemeral_1h_input_tokens: 20 } };
    await writeSession("s1", [
      user("review this PR"),
      { type: "assistant", sessionId: "s1", timestamp: "2026-10-10T10:00:01.000Z", message: { role: "assistant", id: "m1", model: "claude-opus-5-5", usage, content: [{ type: "text", text: "Ok." }] } },
    ]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.sessions[0]!.usage).toEqual({ input: 1, output: 1, cacheRead: 0, cacheWrite: 30, cacheWrite1h: 20 });
  });

  it("leaves usage undefined when no record carries it", async () => {
    await writeSession("s1", [user("hello there")]);
    const [result] = await parseOnly(new ClaudeCodeAdapter(root));
    expect(result!.sessions[0]!.usage).toBeUndefined();
  });

  it("reports a missing root as not found", async () => {
    const d = await new ClaudeCodeAdapter(join(root, "nope")).detect();
    expect(d.found).toBe(false);
  });

  it("groups Conductor workspaces under their repository and records the workspace", async () => {
    const ws = (name: string) => `/Users/jordan/conductor/workspaces/checkout-api/${name}`;
    await writeSession("w1", [user("fix the flaky retry test", { sessionId: "w1", cwd: ws("warsaw-v2") })]);
    await writeSession("w2", [user("add a timeout to the payments client", { sessionId: "w2", cwd: `${ws("lisbon")}/packages/payments` })]);
    await writeSession("plain", [user("rename the config loader", { sessionId: "plain" })]);
    const sessions = (await parseOnly(new ClaudeCodeAdapter(root))).flatMap((r) => r.sessions);
    const by = (id: string) => sessions.find((s) => s.sourceRef.nativeId === id)!;
    expect(by("w1").project?.name).toBe("checkout-api");
    expect(by("w1").harness).toEqual({ name: "conductor", workspace: "warsaw-v2" });
    expect(by("w2").harness).toEqual({ name: "conductor", workspace: "lisbon" });
    expect(by("w2").project).toEqual(by("w1").project);
    expect(by("plain").project?.name).toBe("app");
    expect(by("plain").harness).toBeUndefined();
  });
});
