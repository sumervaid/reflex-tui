import type { Suggestion } from "@reflix/analysis";
import { SOURCE_LABELS, sha256 } from "@reflix/core";
import { assertSlug, findLeaks, redact } from "@reflix/safety";

export const MAX_SKILL_LINES = 150;

export type Provenance = {
  generator: "reflix";
  skill: string;
  suggestion: string;
  createdAt: string;
  confidence: number;
  independentSessions: number;
  records: number;
  repositories: number;
  sources: Record<string, number>;
  firstObserved?: string;
  lastObserved?: string;
  /** Short local session references, e.g. claude-code:7d5ad3da. No paths, no excerpts. */
  sourceSessions: string[];
  steps: string[];
};

export type GeneratedSkill = {
  name: string;
  content: string;
  contentHash: string;
  provenance: Provenance;
};

function shortRef(sessionId: string): string {
  const [source, id = ""] = sessionId.split(/:(.*)/s);
  return `${source}:${id.replace(/[^A-Za-z0-9-]/g, "").slice(0, 8)}`;
}

function yamlString(value: string): string {
  return JSON.stringify(value.replace(/\s+/g, " ").trim());
}

const day = (iso?: string) => (iso ? iso.slice(0, 10) : undefined);

/**
 * Render an approved suggestion as an Agent Skill. Every workflow step comes from the
 * suggestion's consensus steps; nothing is added that the evidence did not show.
 */
export function generateSkill(s: Suggestion, now = new Date()): GeneratedSkill {
  const name = assertSlug(s.slug);
  const sourceNames = Object.keys(s.sources).map((k) => SOURCE_LABELS[k as keyof typeof SOURCE_LABELS] ?? k);
  const refs = [...new Set(s.sourceSessions.map(shortRef))];
  const provenance: Provenance = {
    generator: "reflix",
    skill: name,
    suggestion: s.slug,
    createdAt: now.toISOString(),
    confidence: s.confidence,
    independentSessions: s.instances,
    records: s.records,
    repositories: s.repositories.length,
    sources: s.sources as Record<string, number>,
    firstObserved: day(s.firstSeen),
    lastObserved: day(s.lastSeen),
    sourceSessions: refs,
    steps: s.steps.map((st) => st.kind),
  };

  const description = `${s.description} ${s.whenToUse}`.slice(0, 1000);
  const lines: string[] = [
    "---",
    `name: ${name}`,
    `description: ${yamlString(description)}`,
    "metadata:",
    "  generator: reflix",
    `  created: ${yamlString(day(provenance.createdAt)!)}`,
    `  confidence: ${yamlString(s.confidence.toFixed(2))}`,
    `  independent-sessions: ${yamlString(String(s.instances))}`,
    `  repositories: ${yamlString(String(s.repositories.length))}`,
    `  source-sessions: ${yamlString(refs.slice(0, 12).join(", "))}`,
    "---",
    "",
    `# ${s.title}`,
    "",
    `Generated by Reflix from ${s.instances} independent sessions across ${s.repositories.length} ${s.repositories.length === 1 ? "repository" : "repositories"} (${sourceNames.join(", ")}). ` +
      "Each step below was observed in at least half of those sessions.",
    "",
    "## When to use",
    "",
    s.whenToUse,
    "",
    "## Workflow",
    "",
  ];

  s.steps.forEach((step, i) => {
    let text = `${i + 1}. ${step.instruction}`;
    if (step.variants?.length) text += ` Past fixes were in: ${step.variants.join(", ")}.`;
    lines.push(text);
    if (step.examples.length) lines.push(`   Commands seen: ${step.examples.map((e) => `\`${e}\``).join(", ")}`);
  });

  lines.push("", "## Completion criteria", "");
  for (const c of s.completion) lines.push(`- ${c}`);

  lines.push(
    "",
    "## Notes",
    "",
    "- Placeholders like `<n>`, `<file>` and `<arg>` in commands stand for run numbers, paths and arguments; substitute the real values.",
    "- Use the project's own package manager and scripts if they differ from the commands seen.",
    "- If a step does not apply to the current task, skip it and say so in the summary.",
    "",
    `<!-- reflix: generated ${day(provenance.createdAt)}; confidence ${s.confidence.toFixed(2)} is a ranking heuristic. Run \`reflix explain ${name}\` for local provenance. -->`,
  );

  const content = redact(lines.join("\n")) + "\n";
  const leaks = findLeaks(content);
  if (leaks.length) throw new Error("Generated skill still contains sensitive-looking content; refusing to write it.");
  const lineCount = content.trimEnd().split("\n").length;
  if (lineCount > MAX_SKILL_LINES) throw new Error(`Generated skill is ${lineCount} lines; the limit is ${MAX_SKILL_LINES}.`);
  return { name, content, contentHash: sha256(content), provenance };
}

/** Change the frontmatter name (used when installing under a different name). */
export function renameSkill(content: string, newName: string): string {
  assertSlug(newName);
  const end = content.indexOf("\n---", 3);
  if (!content.startsWith("---\n") || end < 0) throw new Error("Skill file has no frontmatter.");
  const front = content.slice(0, end).replace(/^name: .*$/m, `name: ${newName}`);
  return front + content.slice(end);
}
